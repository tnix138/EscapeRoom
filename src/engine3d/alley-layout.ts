/** آیا این نقطه در بازۀ zِ فرعی است (پایین‌تر از دیوارِ شمالیِ فرعی)؟ */
export function isInBranchBand(z: number): boolean {
  return Number.isFinite(z) && z >= ALLEY_BRANCH.northZ;
}

/** آیا این نقطه در خودِ راهروی فرعی است (غربِ دیوارِ شاخهٔ اصلی)؟ */
export function isInBranch(x: number, z: number): boolean {
  return isInBranchBand(z) && Number.isFinite(x) && x < -ALLEY_MAIN.innerX + 1e-9;
}

