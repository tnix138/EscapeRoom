/**
 * alley-layout.ts — نقشهٔ کوچهٔ L‌شکل تماشاخانهٔ اُرفه‌ئو (امیر)
 * ---------------------------------------------------------------------------
 * خواستهٔ بازبینی: «توی کوچه پشتِ سرمون نرده کشیده شده؛ اون نرده رو بردار، کوچه
 * رو دوبرابر کن و انتهای کوچه یه فرعی به سمتِ چپ درست کن که کوچه L بشه.»
 *
 * پیش‌تر کوچه یک راهروی شمالی–جنوبی بسته بود: از نمای تماشاخانه (z = −۱۴) تا
 * دروازهٔ آهنیِ پشتِ بازیکن (z = +۸٫۸۵). حالا:
 *   • **نرده/دروازهٔ پشتی برداشته شده** — هیچ سدی پشتِ بازیکن نیست.
 *   • **شاخهٔ اصلی (Main) دو برابر شده:** از `northZ = −۱۳٫۲` (نمای تماشاخانه)
 *     تا `southZ = +۳۱` ⇒ ~۴۴ متر به‌جای ~۲۳ متر.
 *   • **فرعیِ غربی (Branch):** در انتهای جنوبی، راهرو به سمتِ چپ (= −X) می‌پیچد:
 *     از `westX = −۳۲` تا دیوارِ داخلیِ شاخهٔ اصلی (`−۸٫۶۵`) و به‌اندازهٔ ۹٫۸ متر
 *     عرض دارد (`northZ = ۲۱٫۲` تا `southZ = ۳۱`) ⇒ کوچه L می‌شود و فرعی بن‌بست است.
 *   • **خیابانِ شرقیِ باز (ALLEY_EAST):** قرینهٔ فرعی در سمتِ راست، پهن‌تر (۱۳ متر)
 *     و **بدونِ بن‌بست**؛ دیوار/درِ انتهایی ندارد و تا دوردستِ مه ادامه دارد.
 *
 * چرا این ماژول؟ همان درسِ پنجره و پرده: هر عددی که هم در هندسه، هم در برخورد و
 * هم در ارتفاعِ گام‌برداری مصرف می‌شود باید یک منبع داشته باشد، وگرنه بازیکن در
 * جایی که دیوار می‌بیند آزادانه راه می‌رود یا در نقطه‌ای که راه باز است گیر می‌کند.
 */

