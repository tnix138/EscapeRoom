/**
 * آیا این نقطه داخلِ باندِ خیابانِ شرقی است؟ (همان شرطی که پروفیلِ کف استفاده
 * می‌کند: از لبهٔ پیاده‌رو به شرق، بینِ دو دیوارِ خیابان)
 */
export function isInEastStreet(x: number, z: number): boolean {
  return (
    Number.isFinite(x) &&
    Number.isFinite(z) &&
    x >= ALLEY_EAST.walkWestX &&
    z >= ALLEY_EAST.northZ &&
    z <= ALLEY_EAST.southZ
  );
}

